#!/usr/bin/env node
/**
 * Generate apps/desktop/src/shared/generated/build-info.ts from package.json
 * and contracts/version.json (PRD v1.1 §12.1).
 */
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "../..");
const DESKTOP_PKG = join(ROOT, "apps/desktop/package.json");
const CONTRACTS_VERSION = join(ROOT, "contracts/version.json");
const OUT_DIR = join(ROOT, "apps/desktop/src/shared/generated");
const OUT = join(OUT_DIR, "build-info.ts");

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function gitCommit() {
  try {
    return execSync("git rev-parse --short HEAD", {
      cwd: ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return "unknown";
  }
}

function main() {
  if (!existsSync(DESKTOP_PKG)) {
    throw new Error(`Missing ${DESKTOP_PKG}`);
  }
  const pkg = readJson(DESKTOP_PKG);
  const contracts = existsSync(CONTRACTS_VERSION) ? readJson(CONTRACTS_VERSION) : {};
  const desktopVersion = String(pkg.version ?? "0.0.0");
  const runtimeApi = String(contracts.runtimeApi ?? "1.3.0");
  // Header negotiation uses major.minor (Serve compatibility historically uses "1.3").
  const runtimeApiVersion = runtimeApi.replace(/\.0$/, "").includes(".")
    ? runtimeApi.split(".").slice(0, 2).join(".")
    : runtimeApi;
  const commit = gitCommit();

  mkdirSync(OUT_DIR, { recursive: true });
  const body = `/* AUTO-GENERATED by tools/release/generate-build-info.mjs — do not edit. */
export const DESKTOP_VERSION = ${JSON.stringify(desktopVersion)} as const;
export const RUNTIME_API_VERSION = ${JSON.stringify(runtimeApiVersion)} as const;
export const RUNTIME_API_FULL_VERSION = ${JSON.stringify(runtimeApi)} as const;
export const GIT_COMMIT = ${JSON.stringify(commit)} as const;
export const CONTRACT_BUNDLE_VERSION = ${JSON.stringify(String(contracts.bundleVersion ?? "0.0.0"))} as const;
`;
  writeFileSync(OUT, body, "utf8");
  console.log(`[generate-build-info] wrote ${OUT}`);
}

main();
